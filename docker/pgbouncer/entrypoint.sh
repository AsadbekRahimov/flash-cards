#!/bin/sh
# Entrypoint of the pgbouncer image (Dockerfile, stage `pgbouncer`): writes pgbouncer.ini and the auth file from the
# environment at every start, then execs pgbouncer in the foreground. docs/DEVOPS_GUIDE.md §0 «pgbouncer и постоянные соединения».
#
# Required: DB_USERNAME, DB_PASSWORD, DB_DATABASE - the very values of .env (compose passes them). Optional, with defaults:
#   PGBOUNCER_DB_HOST / PGBOUNCER_DB_PORT   where PostgreSQL is (compose: postgres:5432)
#   PGBOUNCER_POOL_SIZE                     server connections per database/user pair (default_pool_size)
#   PGBOUNCER_RESERVE_POOL_SIZE             extra server connections when all of the pool are busy for reserve_pool_timeout
#   PGBOUNCER_MAX_CLIENT_CONN               client connections pgbouncer accepts (php-fpm workers + queue workers + ...)
#   PGBOUNCER_QUERY_WAIT_TIMEOUT            seconds a client waits for a free server connection before it gets an error
#   PGBOUNCER_ADMIN_USER / _PASSWORD        a separate console admin (SHUTDOWN, PAUSE, KILL); both or none. Without them nobody
#                                           is admin, and DB_USERNAME may only SHOW (stats_users)
#   PGBOUNCER_CONFIG_DIR                    where the files are written (/etc/pgbouncer)
#
# The auth file holds the plain-text password (mode 0600, written at start, never in the image): with auth_type
# scram-sha-256 pgbouncer then authenticates the clients by SCRAM and logs into PostgreSQL by SCRAM with the same password.
# A SCRAM verifier instead would need the identical salt/iterations as pg_authid (pass-through); the plain text is the
# same secret the postgres and application containers already hold in their environment.

set -eu

: "${DB_USERNAME:?DB_USERNAME is required}"
: "${DB_PASSWORD:?DB_PASSWORD is required}"
: "${DB_DATABASE:?DB_DATABASE is required}"

CONFIG_DIR="${PGBOUNCER_CONFIG_DIR:-/etc/pgbouncer}"
DB_HOST="${PGBOUNCER_DB_HOST:-postgres}"
DB_PORT="${PGBOUNCER_DB_PORT:-5432}"
POOL_SIZE="${PGBOUNCER_POOL_SIZE:-20}"
RESERVE_POOL_SIZE="${PGBOUNCER_RESERVE_POOL_SIZE:-4}"
MAX_CLIENT_CONN="${PGBOUNCER_MAX_CLIENT_CONN:-200}"
QUERY_WAIT_TIMEOUT="${PGBOUNCER_QUERY_WAIT_TIMEOUT:-30}"
LISTEN_PORT="${PGBOUNCER_LISTEN_PORT:-5432}"

for pair in "PGBOUNCER_POOL_SIZE=$POOL_SIZE" "PGBOUNCER_RESERVE_POOL_SIZE=$RESERVE_POOL_SIZE" \
            "PGBOUNCER_MAX_CLIENT_CONN=$MAX_CLIENT_CONN" "PGBOUNCER_QUERY_WAIT_TIMEOUT=$QUERY_WAIT_TIMEOUT" \
            "PGBOUNCER_DB_PORT=$DB_PORT" "PGBOUNCER_LISTEN_PORT=$LISTEN_PORT"; do
    case "${pair#*=}" in
        ''|*[!0-9]*) echo "pgbouncer: ${pair%%=*} must be a whole number, got '${pair#*=}'" >&2; exit 1 ;;
    esac
done
# The database name and the user name go into the ini unquoted: letters, digits and underscore only.
ADMIN_USER="${PGBOUNCER_ADMIN_USER:-}"
ADMIN_PASSWORD="${PGBOUNCER_ADMIN_PASSWORD:-}"
if [ -n "$ADMIN_USER" ] && [ -z "$ADMIN_PASSWORD" ]; then
    echo "pgbouncer: PGBOUNCER_ADMIN_USER needs PGBOUNCER_ADMIN_PASSWORD" >&2; exit 1
fi
case "$DB_DATABASE$DB_USERNAME$ADMIN_USER" in
    *[!A-Za-z0-9_]*) echo "pgbouncer: DB_DATABASE, DB_USERNAME and PGBOUNCER_ADMIN_USER may contain only letters, digits and _" >&2; exit 1 ;;
esac

mkdir -p "$CONFIG_DIR"
umask 077

# Auth file: "user" "password"; a double quote inside a field is written twice.
printf '"%s" "%s"\n' "$(printf '%s' "$DB_USERNAME" | sed 's/"/""/g')" "$(printf '%s' "$DB_PASSWORD" | sed 's/"/""/g')" \
    > "$CONFIG_DIR/userlist.txt"
ADMIN_USERS_LINE=""
if [ -n "$ADMIN_USER" ] && [ "$ADMIN_USER" != "$DB_USERNAME" ]; then
    printf '"%s" "%s"\n' "$ADMIN_USER" "$(printf '%s' "$ADMIN_PASSWORD" | sed 's/"/""/g')" >> "$CONFIG_DIR/userlist.txt"
    ADMIN_USERS_LINE="admin_users = ${ADMIN_USER}"
fi

# max_db_connections caps the server side of this database whatever the pools do: pool + reserve.
MAX_DB_CONNECTIONS=$((POOL_SIZE + RESERVE_POOL_SIZE))

cat > "$CONFIG_DIR/pgbouncer.ini" <<EOF
; Generated by docker/pgbouncer/entrypoint.sh at container start - edit the environment, not this file.
[databases]
${DB_DATABASE} = host=${DB_HOST} port=${DB_PORT} dbname=${DB_DATABASE}

[pgbouncer]
listen_addr = *
listen_port = ${LISTEN_PORT}
unix_socket_dir =
auth_type = scram-sha-256
auth_file = ${CONFIG_DIR}/userlist.txt
${ADMIN_USERS_LINE}
stats_users = ${DB_USERNAME}

; One server connection per transaction; outside a transaction a client holds none. Anything per-session (SET without
; LOCAL, temporary tables, session advisory locks, LISTEN, WITH HOLD cursors) is not for this path - the application uses
; none of them, migrations and pg_dump go to PostgreSQL directly (Laravel connection pgsql_direct).
pool_mode = transaction
max_client_conn = ${MAX_CLIENT_CONN}
default_pool_size = ${POOL_SIZE}
min_pool_size = 2
reserve_pool_size = ${RESERVE_POOL_SIZE}
reserve_pool_timeout = 2
max_db_connections = ${MAX_DB_CONNECTIONS}
query_wait_timeout = ${QUERY_WAIT_TIMEOUT}

; Protocol-level named prepared statements (pgbouncer >= 1.21): the application sends none by default
; (DB_DISABLE_PREPARES=true, unnamed statements), the setting keeps DB_DISABLE_PREPARES=false workable.
max_prepared_statements = 200

; Startup parameters pgbouncer must not reject ("options" is sent by some clients and is not used here). "search_path"
; here means: do not track the application's SET search_path TO "public" per client (pgbouncer 1.26.0 started to, with
; bugs acknowledged in 1.26.1); every client of this pooler sets the same value, and "public" is where everything lives.
; (No backticks in this heredoc: the shell would run them.)
ignore_startup_parameters = extra_float_digits, options, search_path

; After a PostgreSQL restart try to log in again quickly (default 15 s of immediate errors for every client).
server_login_retry = 2
server_lifetime = 3600
server_idle_timeout = 600

log_connections = 0
log_disconnections = 0
log_pooler_errors = 1
EOF

exec "$@"
